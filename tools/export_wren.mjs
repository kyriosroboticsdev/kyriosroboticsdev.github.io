// Copies Wren's desktop page (wren-os: shell/prototype) into public/wren/ for the browser demo.
// public/wren/demo.js stands in for Wren's local service; this script wires the page to it.
// Run after changing the shell:  node tools/export_wren.mjs [path to wren-os]
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { homedir } from "node:os";
import { join } from "node:path";

const repo = process.argv[2] || join(homedir(), "wren-os");
const src = join(repo, "shell", "prototype");
const out = new URL("../public/wren/", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
let html = await readFile(join(src, "index.html"), "utf8");
const commit = (() => { try { return execFileSync("git", ["-C", repo, "rev-parse", "--short", "HEAD"], { encoding: "utf8" }).trim(); } catch { return "unknown"; } })();

// Each edit must hit exactly the expected number of places, so a changed shell fails loudly here
// instead of quietly breaking the demo.
function edit(find, replace, count) {
  const hits = html.split(find).length - 1;
  if (hits !== count) throw new Error(`expected ${count} × ${JSON.stringify(find)}, found ${hits}. The shell changed: update tools/export_wren.mjs`);
  html = html.split(find).join(replace);
}
// The service serves these at the site root; the demo keeps them next to the page.
edit('url("/fonts/inter.woff2")', 'url("fonts/inter.woff2")', 1);
edit('url("/fonts/mono.woff2")', 'url("fonts/mono.woff2")', 1);
edit('"/vendor/', '"vendor/', 3);
// App icons: Flathub's, saved by tools/fetch_wren_store.mjs (launcher keys are "<flathub id>.png").
edit("/store/icon/${encodeURIComponent(a.flathub)}", "store/icon/${encodeURIComponent(a.flathub)}.png", 1);
edit("/launcher/icon/", "store/icon/", 6);
// The stand-in service loads first, so the page's fetch and WebSocket go to it.
edit("\n<script>\n", '\n<script src="demo.js"></script>\n<script>\n', 1);
edit("<title>Wren Desktop</title>", '<title>Wren Desktop · demo</title>\n<meta name="robots" content="noindex">', 1);
html = `<!-- Generated by tools/export_wren.mjs from wren-os ${commit} (shell/prototype). Edit the shell there, then re-run it. -->\n` + html;

await mkdir(join(out, "fonts"), { recursive: true });
await mkdir(join(out, "vendor"), { recursive: true });
await writeFile(join(out, "index.html"), html);
const copies = [
  ["fonts/inter-latin-wght.woff2", "fonts/inter.woff2"], ["fonts/geist-mono-latin-wght.woff2", "fonts/mono.woff2"],
  ["fonts/LICENSE-Inter.txt", "fonts/LICENSE-Inter.txt"], ["fonts/GeistMono-LICENSE.txt", "fonts/GeistMono-LICENSE.txt"],
  ["vendor/xterm.js", "vendor/xterm.js"], ["vendor/xterm.css", "vendor/xterm.css"], ["vendor/xterm-addon-fit.js", "vendor/xterm-addon-fit.js"], ["vendor/xterm-LICENSE.txt", "vendor/xterm-LICENSE.txt"],
];
for (const [a, b] of copies) await copyFile(join(src, a), join(out, b));
console.log(`public/wren/ ← wren-os ${commit}`);
